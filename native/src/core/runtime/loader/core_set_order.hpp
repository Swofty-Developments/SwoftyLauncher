constexpr bool settles(CoreSetId id) { return id != CoreSetId::garage_placement; }

constexpr size_t commit_rank(CoreSetId id)
{
    for (size_t i = 0; i < COMMIT_ORDER.size(); i++)
        if (COMMIT_ORDER[i] == id)
            return i;
    return COMMIT_ORDER.size();
}

