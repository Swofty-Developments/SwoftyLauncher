#!/usr/bin/env python3
"""Write track_keys.inc: the launcher's track table description (packages/core/src/activation/track_tables.json,
the tables, labels and row keys a track's rows are cloned with) for the core's track lowering. Run it after that file
changes; native/test/tracks/run.sh fails while the two differ."""

import json
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
SOURCE = HERE.parents[4] / "packages" / "core" / "src" / "activation" / "track_tables.json"


def render():
    body = json.dumps(json.loads(SOURCE.read_text()), separators=(",", ":"), sort_keys=True)
    chunks = [body[i:i + 8000] for i in range(0, len(body), 8000)]
    out = ["// Generated by track_keys.py from packages/core/src/activation/track_tables.json. Do not edit by hand.",
           "inline constexpr const char *TRACK_TABLES[] = {"]
    out += [f'    R"keys({c})keys",' for c in chunks]
    out.append("};")
    return "\n".join(out) + "\n"


def main():
    target = HERE / "track_keys.inc"
    text = render()
    if "--check" in sys.argv[1:]:
        if not target.exists() or target.read_text() != text:
            raise SystemExit("track_keys.inc is out of date: run native/src/core/apply/tracks/track_keys.py")
        print("track_keys.inc matches track_tables.json")
        return
    target.write_text(text)
    print(f"track_keys.inc: {len(text)} bytes")


if __name__ == "__main__":
    main()
