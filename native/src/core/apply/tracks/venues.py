#!/usr/bin/env python3
"""Write venues.inc: the venue/ ids the core seeds (key, name, country and the stock track code that provides each)
from packages/sdk/std/data/venues.json. Run it after that file changes; --check fails while the two differ and
passes when venues.json is not in this tree. --from reads another file."""

import json
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
SOURCE = HERE.parents[4] / "packages" / "sdk" / "std" / "data" / "venues.json"


def cstr(s):
    return json.dumps(s, ensure_ascii=False)


def render(doc):
    out = ["// Generated by venues.py from packages/sdk/std/data/venues.json. Do not edit by hand.",
           "inline constexpr VenueSeed VENUE_SEEDS[] = {"]
    for key, v in sorted(doc["venues"].items()):
        out.append(f"    {{{cstr(key)}, {cstr(v.get('name') or key)}, {cstr(v.get('country') or '')}, "
                   f"{cstr(v.get('stock') or '')}}},")
    out.append("};")
    return "\n".join(out) + "\n"


def main():
    args = sys.argv[1:]
    source = Path(args[args.index("--from") + 1]) if "--from" in args else SOURCE
    target = HERE / "venues.inc"
    if "--check" in args:
        if not source.exists():
            print(f"venues.inc: {source} is not in this tree; not checked")
            return
        if not target.exists() or target.read_text() != render(json.loads(source.read_text())):
            raise SystemExit("venues.inc is out of date: run native/src/core/apply/tracks/venues.py")
        print("venues.inc matches venues.json")
        return
    doc = json.loads(source.read_text())
    target.write_text(render(doc))
    print(f"venues.inc: {len(doc['venues'])} venue(s)")


if __name__ == "__main__":
    main()
