#!/usr/bin/env python3
"""Build the Ne_Log channel gate table (log_channels.tsv) for the swofty_gamelog core mod.

  logchan.py --out <file>        EXE=<F1_25.exe> re/tools/py re/tools/logchan.py --out native/src/gamelog/log_channels.tsv

The table keeps one section per build (`# F1_25.exe <sha16> <PE timestamp>`); running it on an exe replaces that
build's section and keeps the others. The logger and the gate are found by the core.log_call and core.log_gate
signatures. The exe is a build with a record in re/db/builds, or a flat dump of the running module (the EA builds are
packed on disk): EXE=/mnt/gaming/EAApp/ai-fix/dumps/F1_25.<stamp>.<pid>.mem.

Every Ne_Log_Thunk call site is gated inline by g_Ne_LogGate: the enabled byte, then a probe of the u32 hash set
for a constant per-site hash (`cmp r32, imm32; je <block that calls the logger>`). This walks every function that
calls the logger, pairs each probe hash with the channel string the gated block passes in rcx, and writes one row per
hash: `hash<TAB>sites<TAB>channel[,channel...]` (channels ordered by how many sites use them).
"""
import argparse, collections, hashlib, json, os, re, struct, sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from pe_index import BASE, DATA, EXE, FLAT, SECS, func_of, riprel_refs, rva2off
from capstone import CS_ARCH_X86, CS_MODE_64, Cs

GATE_ENABLED_OFF = 0x5d4
HEADER = '# hash\tsites\tchannels (Ne_Log_Thunk gates, g_Ne_LogGate; one section per build, generated by re/tools/logchan.py)\n'


HERE = os.path.dirname(os.path.abspath(__file__))
RE = os.path.dirname(HERE)
LOG_CALL = os.path.join(RE, 'bindings', 'core', 'Ne_Log_Thunk.json')
LOG_GATE = os.path.join(RE, 'bindings', 'core', 'g_Ne_LogGate.json')
BUILDS = os.path.join(RE, 'db', 'builds')


def pattern_sites(pattern):
    rx = re.compile(b''.join(b'.' if t == '??' else re.escape(bytes([int(t, 16)])) for t in pattern.split()), re.S)
    hits = []
    for _, va, _, ro, rs in SECS:
        for m in rx.finditer(bytes(DATA[ro:ro + rs])):
            hits.append(BASE + va + m.start())
    return hits


def resolve(path):
    sig = json.load(open(path))['signature']
    hits = pattern_sites(sig['pattern'])
    if len(hits) != 1:
        raise SystemExit(f'{sig["id"]}: {len(hits)} matches in this exe, need exactly one')
    r = sig['resolve']
    at = hits[0] + int(r['insn'], 16)
    o = rva2off(at - BASE)
    if r['kind'] == 'rel32':
        return at + 5 + struct.unpack_from('<i', bytes(DATA[o + 1:o + 5]))[0]
    if r['kind'] == 'riprel':
        return at + r['len'] + struct.unpack_from('<i', bytes(DATA[o + 3:o + 7]))[0]
    raise SystemExit(f'{sig["id"]}: unsupported resolve kind {r["kind"]}')


def build_record(stamp):
    for f in sorted(os.listdir(BUILDS)):
        d = json.load(open(os.path.join(BUILDS, f)))
        if d['build']['pe_timestamp'] == stamp:
            return d
    raise SystemExit(f'no build record in re/db/builds for PE timestamp {stamp}')


def cstr(va):
    o = rva2off(va - BASE)
    if o is None:
        return None
    b = bytes(DATA[o:o + 200]).split(b'\0')[0]
    try:
        s = b.decode('ascii')
    except UnicodeDecodeError:
        return None
    return s if s and all(32 <= ord(c) < 127 for c in s) else None


def rip_target(i):
    m = re.search(r'\[rip ([+-]) (0x[0-9a-f]+)\]', i.op_str)
    return i.address + i.size + int(m.group(2), 16) * (1 if m.group(1) == '+' else -1) if m else None


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--out', required=True)
    a = ap.parse_args()
    pe = struct.unpack_from('<I', bytes(DATA[0x3c:0x40]))[0]
    stamp = struct.unpack_from('<I', bytes(DATA[pe + 8:pe + 12]))[0]
    record = build_record(stamp)
    sha = record['build']['sha256']
    if not FLAT and hashlib.sha256(open(EXE, 'rb').read()).hexdigest() != sha:
        raise SystemExit(f'{EXE} is not the exe of build record {record["build"]["distribution"]} {stamp}')
    log = resolve(LOG_CALL)
    gate = resolve(LOG_GATE)
    code = record.get('sections', {}).get('.xtls', '.xtls')
    enabled = gate + GATE_ENABLED_OFF
    site = pattern_sites(json.load(open(LOG_GATE))['signature']['pattern'])[0]
    off = rva2off(site - BASE)
    if bytes(DATA[off:off + 2]) != b'\x80\x3d' or site + 7 + struct.unpack_from('<i', bytes(DATA[off + 2:off + 6]))[0] != enabled:
        raise SystemExit(f'the gate probe does not test the enabled byte at g_Ne_LogGate+{GATE_ENABLED_OFF:#x} in this exe')
    md = Cs(CS_ARCH_X86, CS_MODE_64)
    funcs = sorted({func_of(s) for s, _ in riprel_refs([log - BASE], code) if DATA[rva2off(s - 1)] == 0xE8} - {None})
    per = collections.defaultdict(collections.Counter)
    probes = calls = 0
    for f0, f1 in funcs:
        ins = list(md.disasm(bytes(DATA[rva2off(f0):rva2off(f0) + (f1 - f0)]), BASE + f0))
        at = {x.address: k for k, x in enumerate(ins)}
        if not any(rip_target(x) in (gate, enabled) for x in ins):
            continue
        for k in range(1, len(ins) - 1):
            c, j = ins[k], ins[k + 1]
            m = re.match(r'^(e[a-z]x|e[sd]i|e[sb]p|r\d+d), (0x[0-9a-f]+)$', c.op_str)
            if c.mnemonic != 'cmp' or not m or int(m.group(2), 16) <= 0xfff or j.mnemonic != 'je':
                continue
            if not any(re.search(r'dword ptr \[r\w+ \+ r\w+\*4\]', x.op_str) for x in ins[max(0, k - 4):k]):
                continue
            probes += 1
            h = int(m.group(2), 16)
            t = int(j.op_str, 16) if j.op_str.startswith('0x') else None
            if t not in at:
                per[h][None] += 1
                continue
            ch = None
            for x in ins[at[t]:at[t] + 60]:
                if x.mnemonic == 'lea' and x.op_str.startswith('rcx, [rip'):
                    ch = cstr(rip_target(x))
                if x.mnemonic == 'call' and x.op_str == hex(log):
                    calls += 1
                    break
                if x.mnemonic in ('ret', 'jmp'):
                    ch = None
                    break
            per[h][ch] += 1
    section = [f'# F1_25.exe {sha[:16]} {stamp}\n']
    for h in sorted(per):
        names = [n.replace(',', ';') for n, _ in per[h].most_common() if n]
        section.append(f'{h:#010x}\t{sum(per[h].values())}\t{",".join(names) or "-"}\n')
    keep = []
    if os.path.exists(a.out):
        mine = True
        for line in open(a.out):
            m = re.match(r'^# F1_25\.exe \S+ (\d+)$', line.strip())
            if m:
                mine = int(m.group(1)) != stamp
            if mine and not line.startswith('# hash\t'):
                keep.append(line)
    os.makedirs(os.path.dirname(os.path.abspath(a.out)), exist_ok=True)
    with open(a.out, 'w') as f:
        f.write(HEADER)
        f.writelines(keep)
        f.writelines(section)
    named = sum(1 for c in per.values() if any(c))
    print(f'logchan: {len(funcs)} functions, {probes} gate probes, {calls} reach Ne_Log_Thunk, {len(per)} hashes '
          f'({named} with a channel name) -> {a.out}')


if __name__ == '__main__':
    main()
